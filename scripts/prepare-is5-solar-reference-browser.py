"""Package already accepted solar-reference data without changing scientific inputs."""
from pathlib import Path
import hashlib
import json
import pprint
import shutil

ROOT=Path(__file__).resolve().parents[1]
STAGE=ROOT/'output/is5-solar-reference-browser-staging'
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    # Construction follows the previous candidate's complete product gate.
    gates=['evidence/is5-native-coulomb-20261029c.json',
           'evidence/is5-coulomb-visual-review-20261029c.json',
           'evidence/is5-coulomb-zone-profile-audit-20261029c.json']
    for name in gates:
        receipt=json.loads((ROOT/name).read_text(encoding='utf-8'))
        assert receipt['accepted'],name
        assert all(sha(ROOT/n)==v for n,v in receipt.get('source_sha256',{}).items())
        if 'profile' in receipt:
            profile=ROOT/receipt['profile']
            assert sha(profile)==receipt['profile_sha256']
            measured=json.loads(profile.read_text(encoding='utf-8'))
            assert measured['completed'] and not measured.get('failure')
            assert all(sha(ROOT/n)==v for n,v in measured['source_sha256'].items())
    originals=ROOT/'evidence/is5-solar-reference-20261027a.json'
    brackets=ROOT/'evidence/is5-solar-reference-audit-20261027b.json'
    imported=json.loads(originals.read_text());audit=json.loads(brackets.read_text())
    for receipt in (imported,audit):
        assert receipt['accepted']
        assert all(sha(ROOT/n)==v for n,v in receipt['source_sha256'].items())
    destination=STAGE/'references'
    if destination.exists() or (STAGE/'is5_reference_manifest.py').exists():
        raise FileExistsError('Preserve packed solar references')
    destination.mkdir(parents=True)
    files={}
    for row in imported['models']:
        src=ROOT/row['path'];assert sha(src)==row['sha256']
        name=row['model']+'.json';shutil.copy2(src,destination/name);files[name]=sha(src)
    for row in audit['comparison']:
        src=ROOT/row['path'];assert sha(src)==row['sha256']
        name=src.name;shutil.copy2(src,destination/name);files[name]=sha(src)
    provenance=dict(title='Solar Models ICE2023 / SF-III',version='B23v1.2',
                    authors=['Y. Herrera','A. Serenelli'],code='GarStEC',
                    license='CC BY 4.0',
                    doi='10.5281/zenodo.10822316',url='https://zenodo.org/records/10822316',
                    original_receipt_sha256=sha(originals),ideal_bracket_receipt_sha256=sha(brackets),
                    scope='Modelos de referência; sem evolução, interpolação ou calibração pelo Cosmos2.')
    manifest='# Pinned data copied from accepted receipts; generated by the packing recipe.\n'
    for name,value in [('MODELS',tuple(row['model'] for row in imported['models'])),('FILES',files),('PROVENANCE',provenance)]:
        manifest+=name+' = '+pprint.pformat(value,sort_dicts=True)+'\n'
    (STAGE/'is5_reference_manifest.py').write_text(manifest,encoding='utf-8')
    shutil.copy2(ROOT/'output/is5-solar-reference-staging/README-original-0.txt',STAGE/'README-B23-original.txt')
    shutil.copy2(ROOT/'output/is5-solar-reference-staging/record-10822316.json',STAGE/'B23-metadata-original.json')
    print(json.dumps(dict(files=len(files),models=6,rows=12006,ideal_brackets=713,stage=str(STAGE))))


if __name__=='__main__':main()
